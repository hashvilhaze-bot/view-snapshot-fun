export function createTrekCatalog(): Trek[] {
  return profiles.map((profile) => {
    const itinerary = examples[profile.slug]!;
    const copy = trekCopy[profile.slug]!;
    const walkingDays = itinerary.stages.filter((stage) => stage.kind === "walk").length;
    return {
      ...profile,
      days: walkingDays + " ימי הליכה",
      trekDaysMin: walkingDays,
      trekDaysMax: walkingDays,
      altitude: itinerary.altitude,
      teaser: itinerary.description,
      intro: itinerary.description,
      highlights: copy.highlights,
      surprise: copy.insight,
      details: copy.preparation,
    };
  });
}
