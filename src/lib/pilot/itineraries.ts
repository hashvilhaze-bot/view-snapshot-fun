export function parseStages(raw: string | null): Stage[] | undefined {
  if (!raw) return undefined;
  try {
    const value: unknown = JSON.parse(raw);
    if (!Array.isArray(value) || value.length === 0 || value.length > 60) return undefined;
    const ids = new Set<string>();
    for (const s of value) {
      if (
        !s ||
        typeof s !== "object" ||
        !["id", "start", "end", "time", "story"].every((k) => typeof s[k] === "string") ||
        !["walk", "transfer", "acclimatization"].includes(s.kind) ||
        !s.id ||
        ids.has(s.id)
      )
        return undefined;
      ids.add(s.id);
    }
    return value as Stage[];
  } catch {
    return undefined;
  }
}
